"""Contact Forecast R1: the artifact -> report path.

The report is generated by walking the machine-readable artifacts, which is
what makes "negative results are preserved" a structural property rather than
a matter of authorial discipline. These tests build an artifact in which the
challenger LOSES and check that the loss is rendered, with its sign intact.

Synthetic data only.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from forecast.bootstrap import BootstrapDesign
from forecast.forecast_config import (
    BASELINE_LADDER,
    CONTACT_STAGE_DISCLAIMER,
    PRIMARY_COMPARISON,
)
from forecast.report import render_report
from forecast.run_r1_analysis import (
    build_bootstrap_artifact,
    build_metrics_artifact,
)
from forecast.targets import assert_no_banned_metric_language

REFERENCE, CHALLENGER = PRIMARY_COMPARISON


def make_table(*, challenger_wins: bool, seed: int = 21) -> pd.DataFrame:
    """A prediction table with the ladder columns the artifact builders expect."""
    rng = np.random.default_rng(seed)
    rows: list[dict[str, object]] = []
    challenger_noise = 2.0 if challenger_wins else 11.0
    for season in (2023, 2024):
        for cutoff, horizon in ((100, 100), (50, 50)):
            for batter in range(40):
                truth = rng.normal(4.0, 5.0)
                realized = truth + rng.normal(0.0, 7.0)
                rows.append(
                    {
                        "window_id": f"{batter}-{season}-{cutoff}-{horizon}",
                        "batter": batter,
                        "season": season,
                        "cutoff": cutoff,
                        "horizon": horizon,
                        "target_realized_rv_per_100": realized,
                        "target_deserved_rv_per_100": truth + rng.normal(0.0, 3.0),
                        "std_realized_rv_per_100": truth + rng.normal(0.0, 6.0),
                        "std_deserved_rv_per_100": truth + rng.normal(0.0, 3.0),
                        "league_mean": 4.0,
                        "raw_realized_persistence": truth + rng.normal(0.0, 6.0),
                        "raw_deserved_persistence": truth + rng.normal(0.0, 4.0),
                        REFERENCE: truth + rng.normal(0.0, 6.0),
                        CHALLENGER: truth + rng.normal(0.0, challenger_noise),
                    }
                )
    return pd.DataFrame(rows)


def build_artifacts(table: pd.DataFrame) -> tuple[dict, dict]:
    metrics = build_metrics_artifact(table, {"n_windows": int(len(table))})
    bootstrap = build_bootstrap_artifact(table, design=BootstrapDesign(reps=30, seed=1))
    return metrics, bootstrap


def empty_regression_artifact() -> dict:
    return {
        "regression_direction_by_cell": {},
        "direction_probability": {
            "event": "decline",
            "training_rule": "fit on strictly earlier seasons",
            "models": {},
            "cells": {},
        },
    }


# --------------------------------------------------------------------------
# Negative results survive the write-up
# --------------------------------------------------------------------------


def test_a_losing_challenger_is_rendered_as_losing() -> None:
    table = make_table(challenger_wins=False)
    metrics, bootstrap = build_artifacts(table)
    cell = metrics["cells"]["target_realized_rv_per_100|K100_H100"]
    pooled = cell["comparisons"][CHALLENGER]["pooled_window_weighted"]
    assert pooled["delta_mae"] > 0
    assert pooled["direction_mae"] == "reference_better"

    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    assert "realized better" in report
    # The positive delta is printed as printed, not re-oriented.
    assert f"{pooled['delta_mae']:.4f}" in report


def test_the_report_never_prints_a_reversed_delta() -> None:
    for challenger_wins in (True, False):
        table = make_table(challenger_wins=challenger_wins)
        metrics, bootstrap = build_artifacts(table)
        report = render_report(
            metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
        )
        for key, cell in metrics["cells"].items():
            if cell.get("status") == "no_windows":
                continue
            for comparison in cell["comparisons"].values():
                if comparison.get("status") != "measured":
                    continue
                delta = comparison["pooled_window_weighted"]["delta_mae"]
                # Matched as a whole table cell, so "-0.66" is not mistaken
                # for a match on "0.66".
                assert f"| {delta:.4f} |" in report, key
                if delta != 0.0:
                    assert f"| {-delta:.4f} |" not in report, key


def test_every_measured_comparison_reaches_the_report() -> None:
    table = make_table(challenger_wins=True)
    metrics, bootstrap = build_artifacts(table)
    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    measured = 0
    for cell in metrics["cells"].values():
        if cell.get("status") == "no_windows":
            continue
        for challenger, comparison in cell["comparisons"].items():
            if comparison.get("status") != "measured":
                continue
            measured += 1
            assert f"`{challenger}`" in report
    assert measured == len(BASELINE_LADDER[1:]) * 2 * 2  # rungs x cells x targets
    assert report.count("| deserved |") + report.count("| realized |") >= measured


def test_the_full_ladder_including_the_constant_rung_is_reported() -> None:
    table = make_table(challenger_wins=True)
    metrics, bootstrap = build_artifacts(table)
    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    assert "`league_mean`" in report
    # A constant predictor's correlations must read as undefined, not as 0.
    assert "undefined (undefined_constant_predictor)" in report


