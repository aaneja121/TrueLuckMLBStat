def test_the_report_passes_the_banned_phrase_guard() -> None:
    """Only the disclaimer's own negated use of the phrase is exempt."""
    table = make_table(challenger_wins=True)
    metrics, bootstrap = build_artifacts(table)
    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    assert_no_banned_metric_language(report.replace(CONTACT_STAGE_DISCLAIMER, ""))


def test_the_focal_view_is_marked_without_narrowing_the_specification() -> None:
    """100 -> 100 leads the report but does not outrank the other cutoffs.

    The pre-designation claim is not provable from repository history, so the
    original multi-cutoff specification stands and this cell is a presentation
    view only.
    """
    table = make_table(challenger_wins=False)
    metrics, bootstrap = build_artifacts(table)
    focal = metrics["specification"]["focal_presentation_view"]
    assert focal["cutoff"] == 100
    assert focal["horizon"] == 100
    assert focal["designation_provable_from_repository_history"] is False
    assert "NOT a narrowing" in focal["status"]
    assert focal["primary_family_unchanged"] == [50, 100, 150, 200]
    assert focal["no_conclusion_rests_on_this_cell"] is True
    assert metrics["cells"]["target_realized_rv_per_100|K100_H100"]["is_focal_presentation_view"]
    assert not metrics["cells"]["target_realized_rv_per_100|K50_H50"]["is_focal_presentation_view"]

    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    assert "*(focal view)*" in report
    assert "presentation view only" in report


