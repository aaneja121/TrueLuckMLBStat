def test_a_cell_with_no_windows_is_recorded_not_omitted() -> None:
    table = make_table(challenger_wins=True)
    metrics, _ = build_artifacts(table)
    # The grid has eight cells per target; only two carry synthetic windows.
    empty = [c for c in metrics["cells"].values() if c.get("status") == "no_windows"]
    assert empty
    for cell in empty:
        assert cell["n_windows"] == 0
        assert "cutoff" in cell and "horizon" in cell


def test_undefined_correlations_serialize_as_null_not_zero() -> None:
    table = make_table(challenger_wins=True)
    metrics, _ = build_artifacts(table)
    cell = metrics["cells"]["target_realized_rv_per_100|K100_H100"]
    league = next(m for m in cell["ladder_pooled"]["metrics"] if m["predictor"] == "league_mean")
    assert league["pearson"] is None
    assert league["spearman"] is None
    assert league["mae"] > 0


def test_a_rung_constant_within_each_season_is_labelled_as_such() -> None:
    """`league_mean` varies across seasons only; that must not read as skill."""
    table = make_table(challenger_wins=True)
    metrics, bootstrap = build_artifacts(table)
    # Give each season its own league mean, as the real ladder does.
    table.loc[table["season"] == 2023, "league_mean"] = 3.9
    table.loc[table["season"] == 2024, "league_mean"] = 4.3
    metrics, bootstrap = build_artifacts(table)

    cell = metrics["cells"]["target_realized_rv_per_100|K100_H100"]
    league = next(m for m in cell["ladder_pooled"]["metrics"] if m["predictor"] == "league_mean")
    assert league["constant_within_every_season"] is True
    assert league["pearson"] is not None  # pooled, it does vary
    # Per season it is genuinely constant, so the correlation is undefined.
    for season_entry in cell["ladder_by_season"].values():
        seasonal = next(m for m in season_entry["metrics"] if m["predictor"] == "league_mean")
        assert seasonal["pearson"] is None
        assert seasonal["pearson_status"] == "undefined_constant_predictor"

    report = render_report(
        metrics=metrics, bootstrap=bootstrap, regression=empty_regression_artifact()
    )
    assert "between-season variation only" in report
