"""Contact Forecast R1: run the prespecified analysis and write every artifact.

This is the entry point for R1's descriptive stage. It fits NO forecasting
model -- no ridge, no gradient boosting, nothing beyond the frozen baseline
ladder, the matched shrinkage the ladder already specifies, and the
regression-direction experiment's ordinary least squares and its logistic
direction-probability mapping. Those are the analysis, not a candidate
forecaster.

What it produces, all under `forecast_config.FORECAST_OUTPUTS_DIR`:

  - `r1_prediction_table.parquet` -- one row per window with both targets,
    the pre-cutoff features and every ladder rung. Everything else is derived
    from this, so re-running any single analysis needs only this file.
  - `r1_metrics.json` -- every prespecified cell, every ladder rung, per
    season and pooled, with the macro-average and the batter-balanced
    sensitivity.
  - `r1_bootstrap.json` -- paired, globally batter-clustered intervals.
  - `r1_regression_direction.json` -- the regression-direction experiment,
    its permutation placebo, and the walk-forward decline-probability models.
  - `r1_report.md` -- the human-readable report, generated from those
    artifacts and from nothing else.

## Negative results are structural here, not a matter of discipline

The report is generated by walking the artifact, so a cell cannot be omitted
from the write-up without being omitted from the data. Cells where realized
beats deserved, where an interval crosses zero, where a correlation is weak,
and where the placebo explains the whole regression-direction signal are
rendered by the same code path as favourable ones.
"""

