def build_development_windows(
    *,
    seasons: tuple[int, ...] = FORECAST_ANALYSIS_SEASONS,
    data_dir: Path = FORECAST_DATA_DIR,
) -> tuple[pd.DataFrame, dict[str, Any]]:
    """The 100 -> 200 development windows, with the frozen ladder attached."""
    assert_phase2_seasons_allowed(list(seasons))
    table, audit = build_prediction_table(
        seasons=seasons, data_dir=data_dir, cutoffs=(H200_CUTOFF,), horizons=(H200_HORIZON,)
    )
    return table, audit


def select_h200_alpha(table: pd.DataFrame) -> dict[str, Any]:
    """Select alpha by the FROZEN season-forward procedure, on the H=200 target.

    The procedure is the ridge stage's, unchanged: fit every candidate in the
    frozen `ALPHA_GRID` on 2022, score on 2023 by MAE, take the minimum. Only
    the target window differs. 2024 takes no part in selection, and 2026 is not
    read at all.
    """
    train = table[table["season"].astype(int) == 2022]
    validate = table[table["season"].astype(int) == 2023]
    if train.empty or validate.empty:
        raise H200SpecError("Alpha selection needs both a 2022 and a 2023 fold")
    selection = select_alpha(
        train, validate, model_name=H200_MODEL, target=H200_TARGET, alphas=ALPHA_GRID
    )
    selection["procedure_source"] = (
        "forecast.ridge.select_alpha -- the frozen ridge stage's procedure, unchanged"
    )
    selection["evaluation_season_used_in_selection"] = False
    selection["prospective_season_used_in_selection"] = False
    return selection


def fit_final_h200_model(table: pd.DataFrame, *, alpha: float) -> dict[str, Any]:
    """Fit the final H=200 model on every permitted development season.

    Trained on 2022-2024, matching the Phase 2 pattern for H=100: the seasons
    held out during development become legitimate training data for a
    prospective test. 2025 is sealed; 2026 is never fitted on.
    """
    train = table[table["season"].astype(int).isin(PHASE2_PERMITTED_TRAINING_SEASONS)]
    assert_phase2_seasons_allowed(sorted(int(s) for s in train["season"].unique()))
    if train.empty:
        raise H200SpecError("No permitted development windows to fit the final model on")
    fit = fit_ridge(train, model_name=H200_MODEL, alpha=alpha, target=H200_TARGET)
    record = fit.as_record()
    record["n_features"] = len(fit.features)
    record["target_column"] = H200_TARGET
    record["target_definition"] = (
        f"realized contact-result RV/100 over the next {H200_HORIZON} resolved "
        f"eligible BBE after the first {H200_CUTOFF}"
    )
    record["fitted_on"] = list(PHASE2_PERMITTED_TRAINING_SEASONS)
    record["prospective_season_used_in_fit"] = False
    return record


