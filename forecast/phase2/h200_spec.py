def _cutoff_side_survivorship(
    features: pd.DataFrame, completion: pd.DataFrame, *, label: str
) -> dict[str, Any]:
    """Completion rate and how completers differ from non-completers AT THE CUTOFF.

    Uses only information available at the cutoff plus whether the hitter went
    on to accumulate the horizon. No target value is read.
    """
    merged = features.merge(
        completion[["batter", "season", "reached_cutoff", "completed_horizon"]],
        on=["batter", "season"],
        how="left",
    )
    reached = merged[merged["reached_cutoff"].fillna(False)]
    completers = reached[reached["completed_horizon"].fillna(False)]
    non_completers = reached[~reached["completed_horizon"].fillna(False)]

    feature_names, _ = resolve_features(FEATURE_SETS[H200_MODEL], reached)
    audited = ["std_realized_rv_per_100", "std_deserved_rv_per_100", *feature_names]
    differences: list[dict[str, Any]] = []
    for name in dict.fromkeys(audited):
        if name not in reached.columns:
            continue
        a = pd.to_numeric(completers[name], errors="coerce").dropna()
        b = pd.to_numeric(non_completers[name], errors="coerce").dropna()
        pooled_sd = float(pd.to_numeric(reached[name], errors="coerce").std(ddof=1))
        gap = float(a.mean() - b.mean()) if len(a) and len(b) else float("nan")
        differences.append(
            {
                "feature": name,
                "completer_mean": float(a.mean()) if len(a) else None,
                "non_completer_mean": float(b.mean()) if len(b) else None,
                "difference": gap,
                "standardized_difference": (
                    float(gap / pooled_sd)
                    if pooled_sd and np.isfinite(pooled_sd) and pooled_sd > 0
                    else None
                ),
            }
        )
    differences.sort(key=lambda row: -abs(row["standardized_difference"] or 0.0))
    n_reached, n_completed = int(len(reached)), int(len(completers))
    return {
        "population": label,
        "n_reaching_100_resolved_bbe": n_reached,
        "n_subsequently_reaching_300_total_resolved_bbe": n_completed,
        "n_not_completing": n_reached - n_completed,
        "completion_rate": (float(n_completed) / n_reached if n_reached else float("nan")),
        "cutoff_side_differences": differences,
        "largest_standardized_differences": differences[:5],
        "generalization_note": (
            f"An H={H200_HORIZON} result generalizes ONLY to hitters who subsequently "
            f"accumulate {H200_HORIZON} additional resolved eligible batted balls. It "
            "does not describe the hitters who did not, and it does not predict "
            "playing time, injury, roster survival or demotion."
        ),
    }


def development_survivorship(
    *, seasons: tuple[int, ...] = FORECAST_ANALYSIS_SEASONS, data_dir: Path = FORECAST_DATA_DIR
) -> dict[str, Any]:
    """The H=200 survivorship audit on development seasons."""
    per_season: dict[str, Any] = {}
    frames: list[pd.DataFrame] = []
    completions: list[pd.DataFrame] = []
    for season in seasons:
        ledger = pd.read_parquet(data_dir / f"walk_forward_ledger_{season}.parquet")
        resolved, _ = select_scored_eligible_events(ledger)
        ordered = order_events_for_phase2(resolved)
        features = build_window_features(ordered, H200_CUTOFF)
        completion = horizon_completion(ordered, cutoff=H200_CUTOFF, horizon=H200_HORIZON)
        per_season[str(season)] = _cutoff_side_survivorship(
            features, completion, label=f"development {season}"
        )
        frames.append(features)
        completions.append(completion)
    pooled = _cutoff_side_survivorship(
        pd.concat(frames, ignore_index=True),
        pd.concat(completions, ignore_index=True),
        label="development 2022-2024 pooled",
    )
    return {"pooled": pooled, "by_season": per_season}


def prospective_cutoff_audit(*, snapshot_label: str | None = None) -> dict[str, Any]:
    """The 2026 survivorship audit -- CUTOFF-SIDE ONLY, no target is computed.

    Reads who reached 100 resolved BBE, who went on to 300, and how those two
    groups differ at the cutoff. It never builds an H=200 window and never
    touches a next-200-BBE outcome.
    """
    snapshot = resolve_snapshot(label=snapshot_label)
    ledger, _ = load_contact_stage_ledger(snapshot)
    resolved, _ = select_scored_eligible_events(ledger)
    ordered = order_events_for_phase2(resolved)
    features = build_window_features(ordered, H200_CUTOFF)
    completion = horizon_completion(ordered, cutoff=H200_CUTOFF, horizon=H200_HORIZON)

    audit = _cutoff_side_survivorship(features, completion, label="prospective 2026")
    audit["snapshot_label"] = snapshot.label
    audit["snapshot_data_through"] = snapshot.data_through_date
    audit["h200_outcomes_opened"] = False
    audit["what_was_read"] = (
        "cutoff-side features from the first 100 resolved BBE, plus whether the hitter "
        "subsequently accumulated 200 more. No next-200-BBE run value was computed."
    )
    assert_no_prospective_target(audit)
    return audit


def assert_no_prospective_target(audit: dict[str, Any]) -> None:
    """Prove the prospective audit carries no H=200 outcome.

    Raises:
        H200SpecError: If any target-like key appears in the audit.
    """
    forbidden = ("target_", "_rv_per_100_next", "outcome_value")

    def _walk(node: Any) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                if any(
                    key.startswith(f) or f in key for f in ("target_realized", "target_deserved")
                ):
                    raise H200SpecError(
                        f"The prospective cutoff audit carries {key!r}, which is an "
                        "H=200 outcome. 2026 outcomes must not be opened yet."
                    )
                _walk(value)
        elif isinstance(node, list):
            for item in node:
                _walk(item)

    _walk(audit)
    del forbidden


