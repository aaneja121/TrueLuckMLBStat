def _json_default(value: Any) -> Any:
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        number = float(value)
        return number if np.isfinite(number) else None
    if isinstance(value, np.bool_):
        return bool(value)
    if isinstance(value, np.ndarray):
        return value.tolist()
    raise TypeError(f"{type(value)!r} is not JSON-serializable")


def run(
    *,
    outputs_dir: Path = H200_OUTPUTS_DIR,
    research_dir: Path = FORECAST_OUTPUTS_DIR,
    data_dir: Path = FORECAST_DATA_DIR,
    snapshot_label: str | None = None,
) -> dict[str, Path]:
    """Build, write and freeze the H=200 specification. Opens no 2026 outcome."""
    outputs_dir.mkdir(parents=True, exist_ok=True)

    def _write(name: str, payload: dict[str, Any]) -> None:
        (outputs_dir / name).write_text(
            json.dumps(payload, indent=2, sort_keys=True, default=_json_default)
        )

    _write("h200_provenance_answer.json", H200_PROVENANCE_ANSWER)

    table, _ = build_development_windows(data_dir=data_dir)
    alpha_selection = select_h200_alpha(table)
    logger.info(
        "H=200 alpha selected on %s: %s",
        alpha_selection["validation_season"],
        alpha_selection["selected_alpha"],
    )
    model = fit_final_h200_model(table, alpha=float(alpha_selection["selected_alpha"]))
    _write("h200_frozen_model.json", {"alpha_selection": alpha_selection, "model": model})

    development = development_survivorship(data_dir=data_dir)
    _write("h200_development_survivorship.json", development)
    prospective = prospective_cutoff_audit(snapshot_label=snapshot_label)
    _write("h200_prospective_cutoff_audit.json", prospective)

    specification = build_h200_specification(alpha_selection=alpha_selection, model=model)
    _write("h200_specification.json", specification)
    (outputs_dir / "h200_specification_report.md").write_text(
        render_specification_report(
            spec=specification, development=development, prospective=prospective
        )
    )

    from forecast.stage_freeze import freeze_stage

    # The upstream manifests live in the research namespace; copy the frozen
    # stage manifests' hashes in by pointing the freeze at that directory for
    # the chain, while artifacts stay in this one.
    for name in (
        "r1_freeze_manifest.json",
        "ridge_freeze_manifest.json",
        "hgb_freeze_manifest.json",
    ):
        (outputs_dir / name).write_text((research_dir / name).read_text())
    manifest = freeze_stage(h200_freeze_spec(), outputs_dir=outputs_dir)
    logger.info("froze the H=200 specification: %s", manifest["manifest_sha256"])
    return {
        name: outputs_dir / name for name in (*H200_ARTIFACTS, "h200_spec_freeze_manifest.json")
    }


def main(argv: list[str] | None = None) -> int:
    import argparse

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outputs-dir", type=Path, default=H200_OUTPUTS_DIR)
    parser.add_argument("--research-dir", type=Path, default=FORECAST_OUTPUTS_DIR)
    parser.add_argument("--snapshot-label", type=str, default=None)
    args = parser.parse_args(argv)
    written = run(
        outputs_dir=args.outputs_dir,
        research_dir=args.research_dir,
        snapshot_label=args.snapshot_label,
    )
    for name, path in written.items():
        print(f"{name}: {path}")
    return 0


