def extract_h200_key_results(outputs_dir: Path) -> dict[str, Any]:
    """The specification's own key facts, read back from its artifacts."""
    spec = json.loads((outputs_dir / "h200_specification.json").read_text())
    development = json.loads((outputs_dir / "h200_development_survivorship.json").read_text())
    prospective = json.loads((outputs_dir / "h200_prospective_cutoff_audit.json").read_text())
    # The upstream manifests are copied into this namespace so the freeze is
    # self-contained. That copy could go stale if a development stage were ever
    # re-frozen, so it is compared against the LIVE originals here rather than
    # only against itself.
    upstream_live: dict[str, bool] = {}
    for name in (
        "r1_freeze_manifest.json",
        "ridge_freeze_manifest.json",
        "hgb_freeze_manifest.json",
    ):
        live_path = FORECAST_OUTPUTS_DIR / name
        copy_path = outputs_dir / name
        upstream_live[name] = bool(
            live_path.exists()
            and copy_path.exists()
            and json.loads(live_path.read_text()).get("manifest_sha256")
            == json.loads(copy_path.read_text()).get("manifest_sha256")
        )

    return {
        "upstream_copies_match_live_manifests": upstream_live,
        "provenance_answer": spec["provenance_answer"]["answer"],
        "case": spec["provenance_answer"]["case"],
        "selected_alpha": spec["alpha_selection"]["selected_alpha"],
        "n_features": spec["forecast_model_being_evaluated"]["n_features"],
        "n_train": spec["forecast_model_being_evaluated"]["n_train"],
        "trained_on_seasons": spec["forecast_model_being_evaluated"]["trained_on_seasons"],
        "primary_comparison": spec["metrics"]["primary_comparison"],
        "success_classification_keys": sorted(spec["success_classification"]),
        "development_completion_rate": development["pooled"]["completion_rate"],
        "prospective_completion_rate": prospective["completion_rate"],
        "prospective_n_reaching_100": prospective["n_reaching_100_resolved_bbe"],
        "prospective_n_reaching_300": prospective["n_subsequently_reaching_300_total_resolved_bbe"],
        "prospective_outcomes_opened": spec["season_discipline"]["prospective_outcomes_opened"],
        "power_estimate_is_a_threshold": EXPLORATORY_POWER_ESTIMATE["is_a_success_threshold"],
    }


def assert_h200_specification(key_results: dict[str, Any]) -> None:
    """Refuse the freeze if the specification violates its own contract.

    Raises:
        H200SpecError: If the provenance answer changed, if 2026 outcomes were
            opened, or if the exploratory power estimate became a threshold.
    """
    if key_results["provenance_answer"] != "REFIT" or key_results["case"] != 2:
        raise H200SpecError(
            "The recorded provenance answer is no longer REFIT / case 2; the "
            "specification's whole justification rests on it."
        )
    if key_results["prospective_outcomes_opened"]:
        raise H200SpecError(
            "2026 H=200 outcomes have been opened. The specification must be frozen "
            "BEFORE any outcome is read."
        )
    if key_results["power_estimate_is_a_threshold"]:
        raise H200SpecError(
            "The exploratory power estimate has been turned into a success threshold, "
            "which it must never be."
        )
    stale = [
        name
        for name, matches in key_results.get("upstream_copies_match_live_manifests", {}).items()
        if not matches
    ]
    if stale:
        raise H200SpecError(
            f"The copied upstream manifest(s) {stale} no longer match the live frozen "
            "stages. The provenance chain would record a state that no longer exists."
        )
    if set(key_results["success_classification_keys"]) != {
        "established_incremental_success",
        "promising_but_inconclusive",
        "no_evidence_of_incremental_improvement",
        "evidence_against_incremental_value",
    }:
        raise H200SpecError("The success classification is not the prespecified four-way rule")


