"""Contact Forecast: the H=200 forecast specification, frozen on development data.

## The provenance question, answered first

The exploratory 100 -> 200 scoping result was produced by **REFITTING** Model D
on next-200-BBE targets. It was NOT the frozen H=100 coefficients applied to a
longer evaluation window. Measured directly: coefficients differ, standard
-scaler statistics differ, the intercept moves 5.2184 -> 5.8165, and the
training set shrinks 564 -> 336 rows because a 300-BBE requirement qualifies
fewer hitters. Only the feature LIST and the alpha VALUE were inherited.

Case #2 therefore applies, and this module does what that requires: H=200 is
treated as a NEW forecast specification, with its training target, fit
procedure, selected alpha, features, preprocessing and benchmarks frozen on
development data BEFORE any 2026 H=200 outcome is opened.

The frozen H=100 Contact Forecast is untouched. Nothing here modifies it, and
the Phase 2 H=100 result stands exactly as sealed.

## What may and may not be claimed

H=200 was NOT prespecified in R1, whose frozen grid used horizons 50 and 100.
The historical H=200 numbers are exploratory scoping and are labelled as such
everywhere. The `~82 windows` figure from that scoping run is recorded as an
exploratory power estimate ONLY: it is explicitly not a success threshold and
not a stopping rule, and the frozen success classification below makes no
reference to it.

## Season discipline

Development seasons 2022-2024 only. 2025 is sealed. 2026 is opened here for
CUTOFF-SIDE information only -- how many hitters reached 100 resolved BBE, how
many went on to 300, and how the two groups differ at the cutoff. No 2026
H=200 target is computed anywhere in this module, and
`assert_no_prospective_target` proves it on the returned audit.
"""

